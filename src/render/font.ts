const FIRST = 0x20;
const COUNT = 95;
const ADVANCE = 6;
export const CHAR_W = ADVANCE;
export const CHAR_H = 8;

const atlases = new Map<string, HTMLCanvasElement>();

function atlasFor(color: string): HTMLCanvasElement {
  let atlas = atlases.get(color);
  if (atlas) return atlas;
  atlas = document.createElement('canvas');
  atlas.width = COUNT * ADVANCE;
  atlas.height = CHAR_H;
  const ctx = atlas.getContext('2d')!;
  ctx.fillStyle = color;
  for (let i = 0; i < COUNT; i++) {
    for (let col = 0; col < 5; col++) {
      const bits = GLYPHS[i * 5 + col];
      for (let row = 0; row < 8; row++) {
        if (bits & (1 << row)) ctx.fillRect(i * ADVANCE + col, row, 1, 1);
      }
    }
  }
  atlases.set(color, atlas);
  return atlas;
}

export function textWidth(text: string, scale = 1): number {
  return text.length * ADVANCE * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color = '#d8e4ff',
  scale = 1,
): void {
  const atlas = atlasFor(color);
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (let i = 0; i < text.length; i++) {
    let index = text.charCodeAt(i) - FIRST;
    if (index < 0 || index >= COUNT) index = 31; // '?'
    if (index !== 0) {
      ctx.drawImage(atlas, index * ADVANCE, 0, ADVANCE, CHAR_H, cx, cy, ADVANCE * scale, CHAR_H * scale);
    }
    cx += ADVANCE * scale;
  }
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color?: string,
  scale = 1,
): void {
  drawText(ctx, text, cx - textWidth(text, scale) / 2, y, color, scale);
}

export function drawTextRight(
  ctx: CanvasRenderingContext2D,
  text: string,
  right: number,
  y: number,
  color?: string,
  scale = 1,
): void {
  drawText(ctx, text, right - textWidth(text, scale), y, color, scale);
}

/** Breaks text to fit a width in pixels. */
export function wrapText(text: string, maxWidth: number): string[] {
  const maxChars = Math.floor(maxWidth / ADVANCE);
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(' ')) {
    if (line && line.length + word.length + 1 > maxChars) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines;
}
